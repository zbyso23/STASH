//go:build ignore

// gen_assigned writes assigned15.go: the code points assigned (General
// Category other than Cn) in Unicode 15.0.0, taken from the Go standard
// library tables. It refuses to run on a toolchain whose tables are not
// 15.0.0, so the checked-in table never drifts with the Go release.
//
//	go run gen_assigned.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"unicode"
)

func main() {
	if unicode.Version != "15.0.0" {
		log.Fatalf("toolchain Unicode tables are %s, need 15.0.0", unicode.Version)
	}
	cats := []*unicode.RangeTable{unicode.L, unicode.M, unicode.N, unicode.P, unicode.S, unicode.Z,
		unicode.Cc, unicode.Cf, unicode.Co, unicode.Cs}
	var ranges [][2]rune
	start := rune(-1)
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		in := r <= unicode.MaxRune && unicode.In(r, cats...)
		if in && start < 0 {
			start = r
		}
		if !in && start >= 0 {
			ranges = append(ranges, [2]rune{start, r - 1})
			start = -1
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_assigned.go from Go's Unicode 15.0.0 tables. DO NOT EDIT.\n\n")
	b.WriteString("package canonpath\n\n")
	b.WriteString("// assigned15 lists the inclusive ranges of code points whose General\n// Category in Unicode 15.0.0 is not Cn.\n")
	b.WriteString("var assigned15 = [][2]rune{\n")
	for _, r := range ranges {
		fmt.Fprintf(&b, "{0x%04X, 0x%04X},\n", r[0], r[1])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("assigned15.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %d ranges\n", len(ranges))
}
